bool bakeDetailNormalMap(Mesh const& source, Mesh const& lod,
        std::vector<uint32_t> const& lodIndices, DetailBakeOptions const& options,
        DetailBakeResult* result) {
    if (result == nullptr) {
        return false;
    }
    *result = {};
    if (!source.hasNormals() || !source.hasUVs() || !lod.hasNormals() || !lod.hasUVs() ||
            lodIndices.empty() || lodIndices.size() % 3 != 0 || options.size < 2) {
        return false;
    }
    for (uint32_t index: lodIndices) {
        if (index >= lod.positions.size()) {
            return false;
        }
        // A single 2D map can only represent a UV atlas in [0,1]. Tiled layouts (several charts
        // sharing the same UV rectangle at different integer offsets) need an unwrapped atlas or
        // one map per tile, otherwise different surface points overwrite the same texel.
        if (!isAtlasUv(lod.uvs[index])) {
            return false;
        }
    }

    uint32_t const size = options.size;
    NormalTarget sourceTarget;
    sourceTarget.reset(size);
    rasterizeNormals(source, source.indices, size, &sourceTarget);
    dilateNormals(&sourceTarget, options.dilationTexels);

    FrameTarget lodTarget;
    lodTarget.reset(size);
    std::vector<math::float3> tangents(lod.positions.size());
    std::vector<float> signs(lod.positions.size());
    computeUvTangents(lod, lodIndices, &tangents, &signs);
    rasterizeFrames(lod, lodIndices, tangents, signs, size, &lodTarget);

    std::vector<uint8_t> rgba(size_t(size) * size * 4, 0);
    for (size_t texel = 0; texel < size_t(size) * size; ++texel) {
        rgba[texel * 4 + 0] = 128;
        rgba[texel * 4 + 1] = 128;
        rgba[texel * 4 + 2] = 255;
        rgba[texel * 4 + 3] = 0;
    }
    size_t lodTexels = 0;
    size_t coveredTexels = 0;
    size_t validDetailTexels = 0;
    size_t mismatchedTexels = 0;
    double angleSum = 0.0;
    float maxAngle = 0.0f;
    for (size_t texel = 0; texel < size_t(size) * size; ++texel) {
        if (!lodTarget.covered[texel]) {
            continue;
        }
        ++lodTexels;
        uint8_t* const pixel = &rgba[texel * 4];
        if (!sourceTarget.covered[texel]) {
            continue;
        }
        ++coveredTexels;

        math::float3 const n = lodTarget.normals[texel];
        math::float3 const t = lodTarget.tangents[texel];
        math::float3 const b = cross(n, t) * (lodTarget.signs[texel] < 0.0f ? -1.0f : 1.0f);
        math::float3 const h = sourceTarget.normals[texel];

        math::float3 residual{ dot(h, t), dot(h, b), dot(h, n) };
        float const angle = std::acos(std::clamp(dot(h, n), -1.0f, 1.0f));
        float const degrees = angle * (180.0f / 3.14159265358979323846f);

        // A high-poly normal on the back side of the low-poly surface is a UV mismatch, not
        // detail. Keep the map neutral there instead of rotating the normal by more than 90 deg.
        if (residual.z < 0.0f) {
            ++mismatchedTexels;
            residual = math::float3{ 0.0f, 0.0f, 1.0f };
        } else {
            angleSum += degrees;
            maxAngle = std::max(maxAngle, degrees);
            ++validDetailTexels;
            residual = normalizedOr(residual, math::float3{ 0.0f, 0.0f, 1.0f });
            // The alpha channel is a per-texel estimate of how much normal detail the LOD lost.
            // A renderer can fold it into roughness, where the original high-frequency normal
            // distribution would otherwise produce a specular highlight narrower than the mesh.
            pixel[3] = uint8_t(std::clamp(std::lround(degrees * (255.0f / 90.0f)), 0L, 255L));
        }

        pixel[0] = uint8_t(std::clamp(std::lround((residual.x * 0.5f + 0.5f) * 255.0f), 0L, 255L));
        pixel[1] = uint8_t(std::clamp(std::lround((residual.y * 0.5f + 0.5f) * 255.0f), 0L, 255L));
        pixel[2] = uint8_t(std::clamp(std::lround((residual.z * 0.5f + 0.5f) * 255.0f), 0L, 255L));
    }

    if (coveredTexels == 0) {
        return false;
    }

    result->size = size;
    result->rgba = std::move(rgba);
    result->lodTexels = lodTexels;
    result->coveredTexels = coveredTexels;
    result->meanAngleDegrees =
            validDetailTexels > 0 ? float(angleSum / double(validDetailTexels)) : 0.0f;
    result->maxAngleDegrees = maxAngle;
    result->mismatchedTexels = mismatchedTexels;
    return true;
}


bool bakeDetailHeightMap(Mesh const& source, Mesh const& lod,
        std::vector<uint32_t> const& lodIndices, DetailHeightOptions const& options,
        DetailHeightResult* result) {
    if (result == nullptr) {
        return false;
    }
    *result = {};
    if (!lod.hasNormals() || !source.hasUVs() || !lod.hasUVs() ||
            lodIndices.empty() || lodIndices.size() % 3 != 0 || options.size < 2 ||
            source.indices.empty() || source.positions.empty()) {
        return false;
    }
    for (uint32_t index: lodIndices) {
        if (index >= lod.positions.size()) {
            return false;
        }
        if (!isAtlasUv(lod.uvs[index])) {
            return false;
        }
    }

    auto const start = HeightClock::now();

    math::float3 boundsMin{ std::numeric_limits<float>::max() };
    math::float3 boundsMax{ std::numeric_limits<float>::lowest() };
    for (math::float3 const& position: source.positions) {
        boundsMin = min(boundsMin, position);
        boundsMax = max(boundsMax, position);
    }
    float const diagonal = length(boundsMax - boundsMin);
    if (diagonal <= 0.0f) {
        return false;
    }
    float const maximumDistance = options.maximumDistance > 0.0f
            ? options.maximumDistance : 0.05f * diagonal;

    uint32_t const size = options.size;
    HeightTarget sourceTarget;
    sourceTarget.reset(size);
    rasterizeHeightSurface(source, source.indices, size, &sourceTarget);

    HeightTarget lodTarget;
    lodTarget.reset(size);
    rasterizeHeightSurface(lod, lodIndices, size, &lodTarget);

    std::vector<float> heights(size_t(size) * size, 0.0f);
    std::vector<uint8_t> hit(size_t(size) * size, 0);
    size_t lodTexels = 0;
    size_t coveredTexels = 0;
    size_t missedTexels = 0;
    float minHeight = std::numeric_limits<float>::max();
    float maxHeight = std::numeric_limits<float>::lowest();
    double absHeightSum = 0.0;

    for (size_t texel = 0; texel < size_t(size) * size; ++texel) {
        if (!lodTarget.covered[texel]) {
            continue;
        }
        ++lodTexels;
        if (!sourceTarget.covered[texel]) {
            ++missedTexels;
            continue;
        }
        math::float3 const delta = sourceTarget.positions[texel] - lodTarget.positions[texel];
        float const height = dot(delta, lodTarget.normals[texel]);
        if (std::abs(height) > maximumDistance) {
            ++missedTexels;
            continue;
        }
        heights[texel] = height;
        hit[texel] = 1;
        ++coveredTexels;
        minHeight = std::min(minHeight, height);
        maxHeight = std::max(maxHeight, height);
        absHeightSum += double(std::abs(height));
    }

    if (coveredTexels == 0) {
        return false;
    }
    float const heightRange = std::max(std::abs(minHeight), std::abs(maxHeight));
    std::vector<uint8_t> values(size_t(size) * size, 128);
    if (heightRange > 1e-8f) {
        float const scale = 127.5f / heightRange;
        for (size_t texel = 0; texel < size_t(size) * size; ++texel) {
            if (hit[texel]) {
                float const encoded = 127.5f + heights[texel] * scale;
                values[texel] = uint8_t(std::clamp(std::lround(encoded), 0L, 255L));
            }
        }
    }
    dilateHeights(&values, &hit, size, options.dilationTexels);

    double worldArea = 0.0;
    double uvArea = 0.0;
    for (size_t triangle = 0; triangle + 2 < lodIndices.size(); triangle += 3) {
        uint32_t const i0 = lodIndices[triangle + 0];
        uint32_t const i1 = lodIndices[triangle + 1];
        uint32_t const i2 = lodIndices[triangle + 2];
        math::float3 const e1 = lod.positions[i1] - lod.positions[i0];
        math::float3 const e2 = lod.positions[i2] - lod.positions[i0];
        math::float2 const d1 = lod.uvs[i1] - lod.uvs[i0];
        math::float2 const d2 = lod.uvs[i2] - lod.uvs[i0];
        worldArea += 0.5 * double(length(cross(e1, e2)));
        uvArea += 0.5 * double(std::abs(d1.x * d2.y - d2.x * d1.y));
    }
    float const worldPerUv = uvArea > 1e-12 ? float(std::sqrt(worldArea / uvArea)) : 0.0f;

    result->size = size;
    result->values = std::move(values);
    result->lodTexels = lodTexels;
    result->coveredTexels = coveredTexels;
    result->missedTexels = missedTexels;
    result->minHeight = minHeight;
    result->maxHeight = maxHeight;
    result->meanAbsHeight = float(absHeightSum / double(coveredTexels));
    result->heightRange = heightRange;
    result->recommendedUvScale = worldPerUv > 1e-6f ? heightRange / worldPerUv : 0.02f;
    result->bakeMs = std::chrono::duration<double, std::milli>(HeightClock::now() - start).count();
    return true;
}

